let cart = [];

let currentCategory = "All";




function showSection(sectionName) {

    const sections =
        document.querySelectorAll(".page-section");

    sections.forEach(function(section) {

        section.classList.remove(
            "active-section"
        );

    });


    const selectedSection =
        document.getElementById(sectionName);

    if (selectedSection) {

        selectedSection.classList.add(
            "active-section"
        );

    }


    const navLinks =
        document.querySelectorAll(".nav-link");

    navLinks.forEach(function(link) {

        link.classList.remove("active");

    });


    const selectedNav =
        document.getElementById(
            sectionName + "Nav"
        );

    if (selectedNav) {

        selectedNav.classList.add("active");

    }


    document
        .getElementById("navbar")
        .classList.remove("show");


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}




function openCategory(category) {

    showSection("products");

    currentCategory = category;


    const buttons =
        document.querySelectorAll(
            ".category-btn"
        );


    buttons.forEach(function(button) {

        button.classList.remove("active");

        if (
            button.textContent.trim()
            === category
        ) {

            button.classList.add("active");

        }

    });


    displayProducts();

}




function filterCategory(category, button) {

    currentCategory = category;


    const buttons =
        document.querySelectorAll(
            ".category-btn"
        );


    buttons.forEach(function(btn) {

        btn.classList.remove("active");

    });


    button.classList.add("active");


    displayProducts();

}




function displayProducts() {

    const productsGrid =
        document.getElementById(
            "productsGrid"
        );


    const searchInput =
        document.getElementById(
            "searchInput"
        );


    const searchText =
        searchInput.value
            .toLowerCase()
            .trim();


    const filteredProducts =
        products.filter(function(product) {

            const matchesCategory =
                currentCategory === "All"
                ||
                product.category
                    === currentCategory;


            const matchesSearch =
                product.name
                    .toLowerCase()
                    .includes(searchText)
                ||
                product.category
                    .toLowerCase()
                    .includes(searchText);


            return (
                matchesCategory
                &&
                matchesSearch
            );

        });


    productsGrid.innerHTML = "";


    if (
        filteredProducts.length
        === 0
    ) {

        productsGrid.innerHTML = `

            <div class="no-products">

                <i
                    class="fa-solid fa-box-open"
                    style="font-size:45px;">
                </i>

                <h3>
                    No Products Found
                </h3>

                <p>
                    Try another search or category.
                </p>

            </div>

        `;

        return;

    }


    filteredProducts.forEach(
        function(product) {

            const card =
                document.createElement(
                    "div"
                );


            card.className =
                "product-card";


            card.innerHTML = `

                <!-- PRODUCT IMAGE -->

                <div class="product-image">

                    <img
                        src="${product.image}"
                        alt="${product.name}"
                        loading="lazy"
                        onerror="this.onerror=null; this.src='https://placehold.co/500x400?text=Image+Not+Found';"
                    >

                </div>


                <!-- PRODUCT DETAILS -->

                <div class="product-content">

                    <span class="product-category">
                        ${product.category}
                    </span>


                    <h3>
                        ${product.name}
                    </h3>


                    <p>
                        ${product.description}
                    </p>


                    <div class="product-bottom">

                        <span class="price">
                            Rs.
                            ${product.price.toLocaleString()}
                        </span>


                        <button
                            class="add-btn"
                            onclick="addToCart(${product.id})">

                            <i
                                class="fa-solid fa-cart-plus">
                            </i>

                            Add

                        </button>

                    </div>

                </div>

            `;


            productsGrid.appendChild(card);

        }
    );

}




function searchProducts() {

    displayProducts();

}




function addToCart(productId) {

    const product =
        products.find(function(item) {

            return item.id === productId;

        });


    if (!product) {

        return;

    }


    const existingItem =
        cart.find(function(item) {

            return item.id === productId;

        });


    if (existingItem) {

        existingItem.quantity++;

    }

    else {

        cart.push({

            ...product,

            quantity: 1

        });

    }


    updateCart();


    alert(
        product.name +
        " has been added to your cart."
    );

}




function updateCart() {

    const cartCount =
        document.getElementById(
            "cartCount"
        );


    const cartItems =
        document.getElementById(
            "cartItems"
        );


    const cartTotal =
        document.getElementById(
            "cartTotal"
        );


    const finalTotal =
        document.getElementById(
            "finalTotal"
        );


    const totalQuantity =
        cart.reduce(
            function(total, item) {

                return (
                    total +
                    item.quantity
                );

            },
            0
        );


    cartCount.textContent =
        totalQuantity;


    if (cart.length === 0) {

        cartItems.innerHTML = `

            <div class="empty-cart">

                <div class="empty-cart-icon">

                    <i
                        class="fa-solid fa-cart-shopping">
                    </i>

                </div>

                <h3>
                    Your cart is empty
                </h3>

                <p>
                    Add some products to your cart.
                </p>

                <br>

                <button
                    class="primary-btn"
                    onclick="showSection('products')">

                    Start Shopping

                </button>

            </div>

        `;


        cartTotal.textContent =
            "Rs. 0";


        finalTotal.textContent =
            "Rs. 0";


        return;

    }


    cartItems.innerHTML = "";


    cart.forEach(function(item) {

        const cartItem =
            document.createElement(
                "div"
            );


        cartItem.className =
            "cart-item";




        cartItem.innerHTML = `

            <div class="cart-item-image">

                <img
                    src="${item.image}"
                    alt="${item.name}"
                    onerror="this.onerror=null; this.src='https://placehold.co/200x200?text=Image+Not+Found';"
                >

            </div>


            <div class="cart-item-info">

                <h4>
                    ${item.name}
                </h4>

                <p>
                    Rs.
                    ${item.price.toLocaleString()}
                </p>

            </div>


            <div class="quantity-controls">

                <button
                    class="minus-btn"
                    data-id="${item.id}">

                    <i
                        class="fa-solid fa-minus">
                    </i>

                </button>


                <strong>
                    ${item.quantity}
                </strong>


                <button
                    class="plus-btn"
                    data-id="${item.id}">

                    <i
                        class="fa-solid fa-plus">
                    </i>

                </button>

            </div>


            <strong>

                Rs.
                ${(item.price * item.quantity)
                    .toLocaleString()}

            </strong>


            <button
                class="remove-cart"
                data-id="${item.id}"
                aria-label="Remove product">

                <i
                    class="fa-solid fa-trash">
                </i>

            </button>

        `;


        cartItems.appendChild(
            cartItem
        );

    });


    const total =
        cart.reduce(
            function(sum, item) {

                return (
                    sum +
                    item.price *
                    item.quantity
                );

            },
            0
        );


    cartTotal.textContent =
        "Rs. " +
        total.toLocaleString();


    finalTotal.textContent =
        "Rs. " +
        total.toLocaleString();


    attachCartEvents();

}




function attachCartEvents() {

    document
        .querySelectorAll(".plus-btn")
        .forEach(function(button) {

            button.addEventListener(
                "click",
                function() {

                    const id =
                        Number(
                            button.dataset.id
                        );


                    const item =
                        cart.find(function(item) {

                            return item.id === id;

                        });


                    if (item) {

                        item.quantity++;

                        updateCart();

                    }

                }
            );

        });


    document
        .querySelectorAll(".minus-btn")
        .forEach(function(button) {

            button.addEventListener(
                "click",
                function() {

                    const id =
                        Number(
                            button.dataset.id
                        );


                    const item =
                        cart.find(function(item) {

                            return item.id === id;

                        });


                    if (item) {

                        if (
                            item.quantity > 1
                        ) {

                            item.quantity--;

                        }

                        else {

                            cart =
                                cart.filter(
                                    function(cartItem) {

                                        return (
                                            cartItem.id
                                            !== id
                                        );

                                    }
                                );

                        }


                        updateCart();

                    }

                }
            );

        });


    document
        .querySelectorAll(".remove-cart")
        .forEach(function(button) {

            button.addEventListener(
                "click",
                function() {

                    const id =
                        Number(
                            button.dataset.id
                        );


                    cart =
                        cart.filter(
                            function(item) {

                                return (
                                    item.id !== id
                                );

                            }
                        );


                    updateCart();

                }
            );

        });

}




